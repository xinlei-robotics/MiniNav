def write_path_csv(points, path: Path, comment: str = "") -> Path:
    """写 `sim nav --path` 可读的折线(x,y 两列;朝向由 sim 按线段方向补)。"""
    lines = [f"# {comment}"] if comment else []
    lines.append("x,y")
    lines += [f"{x!r},{y!r}" for x, y in points]
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path


# ---- 运行 sim nav ---------------------------------------------------------------

def parse_header(lines) -> dict:
    meta: dict = {}
    for line in lines:
        if not line.startswith("#"):
            break
        body = line[1:].strip()
        if "=" in body:
            key, value = body.split("=", 1)
            meta[key.strip()] = _parse_scalar(value.strip())
    return meta


def run_nav(sim: Path, out_csv: Path, *, map_yaml: str | None = None, path_csv: Path | None = None,
            start: str | None = None, goal: str | None = None, seed: int = 1, preset: str = "default",
            controller_input: str = "ekf", robot: Path | None = None, nav: Path | None = None,
            max_time: float | None = None) -> dict:
    """跑一次 `sim nav --no-viz`,返回 nav.csv 的头部元数据(status、误差、净空……)。"""
    cmd = [str(sim), "nav", "--no-viz", "--out", str(out_csv), "--seed", str(seed),
           "--preset", preset, "--controller-input", controller_input]
    if map_yaml is not None:
        cmd += ["--map", str(map_yaml)]
    if path_csv is not None:
        cmd += ["--path", str(path_csv)]
    if start is not None:
        cmd += ["--start", start]
    if goal is not None:
        cmd += ["--goal", goal]
    if robot is not None:
        cmd += ["--robot", str(robot)]
    if nav is not None:
        cmd += ["--nav", str(nav)]
    if max_time is not None:
        cmd += ["--max-time", repr(max_time)]
    Path(out_csv).parent.mkdir(parents=True, exist_ok=True)
    proc = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"sim nav failed ({proc.returncode}):\n{' '.join(cmd)}\n{proc.stdout}{proc.stderr}")
    with open(out_csv) as f:
        return parse_header(f)


def read_nav_csv(path: Path) -> tuple[dict, pd.DataFrame]:
    """nav.csv(或 save_slim 写的 .csv.gz)→ (头部元数据, 数据表)。"""
    opener = gzip.open if str(path).endswith(".gz") else open
    with opener(path, "rt") as f:
        meta = parse_header(f)
    df = pd.read_csv(path, comment="#")
    return meta, df


def run_and_load(sim: Path, out_csv: Path, keep: bool = False, **kwargs) -> tuple[dict, pd.DataFrame]:
    """run_nav + read_nav_csv;keep = False 时读完即删(全精度 nav.csv 每分钟约 6 MB)。"""
    run_nav(sim, out_csv, **kwargs)
    meta, df = read_nav_csv(out_csv)
    if not keep:
        Path(out_csv).unlink()
    return meta, df


