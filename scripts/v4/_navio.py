# χ² 分位数:dof 1 / 2 的 95% 双侧区间(与 scripts/v2/analyze_ekf.py 同值)。
CHI2_95 = {1: (0.000982, 5.023886), 2: (0.050636, 7.377759)}


def chi2_quantile(p: float, dof: int) -> float:
    """χ² 分位数的 Wilson–Hilferty 近似(dof ≥ 10 时相对误差 < 1%),只用于多次运行的平均。"""
    # 只需要这几个标准正态分位数,直接查表(不为此引入 scipy)。
    z = {0.025: -1.959964, 0.975: 1.959964, 0.05: -1.644854, 0.95: 1.644854}[p]
    k = float(dof)
    return k * (1.0 - 2.0 / (9.0 * k) + z * math.sqrt(2.0 / (9.0 * k))) ** 3
