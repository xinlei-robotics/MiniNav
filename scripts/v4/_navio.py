def save_slim(meta: dict, df: pd.DataFrame, path: Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(path, "wt") as f:
        for key, value in meta.items():
            f.write(f"# {key} = {value}\n")
        df[list(SLIM_COLUMNS)].to_csv(f, index=False, float_format="%.7g")
    return path


def traveled(df: pd.DataFrame) -> np.ndarray:
    """真值走过的路程 s(t)(每行是推进前的快照,所以首行 s = 0)。"""
    step = np.hypot(np.diff(df["truth_x"].to_numpy()), np.diff(df["truth_y"].to_numpy()))
    return np.concatenate([[0.0], np.cumsum(step)])


# ---- 折线几何 -------------------------------------------------------------------

def signed_cross_track(points: np.ndarray, polyline: np.ndarray) -> np.ndarray:
    """点到折线的距离,按最近线段的左右定号(左正)。

    points: (N, 2);polyline: (M, 2)。最近点落在拐点上时,用相邻两段中较近的那段定号;
    对左转的转角,内侧(切角)为正,出弯后越到外侧为负。"""
    p = np.asarray(points, dtype=float)[:, None, :]
    a = np.asarray(polyline[:-1], dtype=float)[None, :, :]
    b = np.asarray(polyline[1:], dtype=float)[None, :, :]
    ab = b - a
    t = np.clip(np.sum((p - a) * ab, axis=2) / np.sum(ab * ab, axis=2), 0.0, 1.0)
    closest = a + t[..., None] * ab
    dist = np.linalg.norm(p - closest, axis=2)
    seg = np.argmin(dist, axis=1)
    rows = np.arange(p.shape[0])
    d = dist[rows, seg]
    rel = p[:, 0, :] - a[0, seg]
    cross = ab[0, seg, 0] * rel[:, 1] - ab[0, seg, 1] * rel[:, 0]
    return np.where(cross >= 0.0, d, -d)


def occupied_centers(grid: Grid) -> np.ndarray:
    ys, xs = np.nonzero(grid.occ == K_OCCUPIED)
    return np.column_stack([grid.origin[0] + (xs + 0.5) * grid.resolution,
                            grid.origin[1] + (ys + 0.5) * grid.resolution])


def clearance(points: np.ndarray, grid: Grid, radius: float, cap: float = 0.5,
              centers: np.ndarray | None = None) -> np.ndarray:
    """圆(圆心 points、半径 radius)到最近占据方块的净空,与 C++ footprint_clearance 同义。"""
    centers = occupied_centers(grid) if centers is None else centers
    half = 0.5 * grid.resolution
    out = np.empty(len(points))
    for i, (x, y) in enumerate(np.asarray(points, dtype=float)):
        near = centers[(np.abs(centers[:, 0] - x) <= radius + cap + half)
                       & (np.abs(centers[:, 1] - y) <= radius + cap + half)]
        if len(near) == 0:
            out[i] = cap
            continue
        dx = np.maximum(np.abs(x - near[:, 0]) - half, 0.0)
        dy = np.maximum(np.abs(y - near[:, 1]) - half, 0.0)
        out[i] = min(float(np.min(np.hypot(dx, dy))) - radius, cap)
    return out


def densify(polyline: np.ndarray, step: float) -> np.ndarray:
    """按弧长等距重采样折线(含两端点)。"""
    pts = [polyline[0]]
    for a, b in zip(polyline[:-1], polyline[1:]):
        n = max(1, int(math.ceil(np.linalg.norm(b - a) / step)))
        for k in range(1, n + 1):
            pts.append(a + (b - a) * k / n)
    return np.asarray(pts)


def xy_of(pose: str) -> str:
    """"x,y[,yaw]" → "x,y"(`sim plan` 只接受位置)。"""
    return ",".join(pose.split(",")[:2])


def plan_path(sim: Path, map_yaml: str, start: str, goal: str, out_csv: Path, smooth: bool = True) -> np.ndarray:
    """用 `sim plan --smooth` 和 config/nav.yaml 的 planner 段生成 sim nav 会用的同一条
    平滑路径(写到 out_csv),返回 (N, 2) 折线。smooth = False 时返回 A* 原始台阶路径。"""
    planner = read_yaml_subset(REPO / "config" / "nav.yaml")["planner"]
    planner_yaml = write_yaml_subset(planner, Path(out_csv).with_suffix(".planner.yaml"),
                                     "generated by scripts/v4 — the planner section of config/nav.yaml")
    cmd = [str(sim), "plan", "--map", str(map_yaml), "--start", xy_of(start), "--goal", xy_of(goal),
           "--config", str(planner_yaml), "--no-viz", "--out", str(out_csv)] + (["--smooth"] if smooth else [])
    Path(out_csv).parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(cmd, cwd=REPO, check=True, capture_output=True, text=True)
    df = pd.read_csv(out_csv, comment="#")
    return df[["x", "y"]].to_numpy()


