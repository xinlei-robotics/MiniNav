def find_sim(prefer: str = "release") -> Path:
    """返回 sim 的路径:默认 Release(快),找不到回退 Debug。"""
    order = ["clang18-release", "clang18-debug"] if prefer == "release" else ["clang18-debug", "clang18-release"]
    for preset in order:
        candidate = REPO / "build" / preset / "sim"
        if candidate.exists():
            return candidate
    raise FileNotFoundError("sim not found; build first: cmake --build --preset build-release -j")


# ---- YAML 子集 ---------------------------------------------------------------

def _parse_scalar(text: str):
    low = text.lower()
    if low in ("true", "false"):
        return low == "true"
    try:
        return int(text)
    except ValueError:
        pass
    try:
        return float(text)
    except ValueError:
        return text


def read_yaml_subset(path: Path) -> dict:
    """读 config/*.yaml 用到的 YAML 子集:嵌套映射(2 空格缩进)+ 标量,忽略注释。"""
    root: dict = {}
    stack: list[tuple[int, dict]] = [(-1, root)]
    for raw in Path(path).read_text().splitlines():
        line = raw.split("#", 1)[0].rstrip()
        if not line.strip():
            continue
        indent = len(line) - len(line.lstrip())
        key, _, value = line.strip().partition(":")
        while stack[-1][0] >= indent:
            stack.pop()
        parent = stack[-1][1]
        if value.strip():
            parent[key] = _parse_scalar(value.strip())
        else:
            parent[key] = {}
            stack.append((indent, parent[key]))
    return root


def _format_scalar(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return repr(value)
    return str(value)


def write_yaml_subset(cfg: dict, path: Path, comment: str = "") -> Path:
    lines = [f"# {line}" for line in comment.splitlines()] if comment else []

    def emit(node: dict, indent: int) -> None:
        for key, value in node.items():
            if isinstance(value, dict):
                lines.append(" " * indent + f"{key}:")
                emit(value, indent + 2)
            else:
                lines.append(" " * indent + f"{key}: {_format_scalar(value)}")

    emit(cfg, 0)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path


def _merge(base: dict, overrides: dict) -> dict:
    out = {k: (dict(v) if isinstance(v, dict) else v) for k, v in base.items()}
    for key, value in overrides.items():
        if isinstance(value, dict):
            if key not in out or not isinstance(out[key], dict):
                raise KeyError(f"override section '{key}' does not exist in the base config")
            out[key] = _merge(out[key], value)
        else:
            out[key] = value
    return out


def variant_configs(name: str, robot: dict | None = None, nav: dict | None = None,
                    out_dir: Path | None = None) -> tuple[Path, Path]:
    """以仓库默认配置为底,写出只改了 overrides 的 robot / nav 变体,返回两个路径。

    例:variant_configs("ideal", robot={"actuator_time_constant": 0.0},
                         nav={"controller": {"control_frequency": 100.0}})
    """
    out_dir = Path(out_dir or DATA_DIR / "configs")
    base_robot = read_yaml_subset(REPO / "config" / "robot.yaml")
    base_nav = read_yaml_subset(REPO / "config" / "nav.yaml")
    robot_path = write_yaml_subset(_merge(base_robot, robot or {}), out_dir / f"robot_{name}.yaml",
                                   f"generated by scripts/v4 — variant '{name}' of config/robot.yaml")
    nav_path = write_yaml_subset(_merge(base_nav, nav or {}), out_dir / f"nav_{name}.yaml",
                                 f"generated by scripts/v4 — variant '{name}' of config/nav.yaml")
    return robot_path, nav_path


